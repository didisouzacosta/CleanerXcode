#!/usr/bin/env bash
# Writes CleanerXcode/Secrets.xcconfig from the environment for a CI build (C42). It is
# git-ignored and included by Config.xcconfig. Empty variables stay empty, which turns the
# matching feature off (analytics, crash reports, Sparkle). In xcconfig files "//" starts a
# comment, so every "//" becomes "/$()/". Values are never printed.
#
# Reads: HIMETRICA_API_KEY, SENTRY_DSN, SPARKLE_FEED_URL, SPARKLE_PUBLIC_ED_KEY
set -euo pipefail

readonly ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
readonly OUTPUT="$ROOT/CleanerXcode/Secrets.xcconfig"

escape() {
  printf '%s' "$1" | sed 's#//#/$()/#g'
}

umask 077
{
  echo "// Generated by scripts/release/write-secrets-xcconfig.sh. Do not commit."
  echo "HIMETRICA_API_KEY = $(escape "${HIMETRICA_API_KEY:-}")"
  echo "SENTRY_DSN = $(escape "${SENTRY_DSN:-}")"
  echo "SPARKLE_FEED_URL = $(escape "${SPARKLE_FEED_URL:-}")"
  echo "SPARKLE_PUBLIC_ED_KEY = $(escape "${SPARKLE_PUBLIC_ED_KEY:-}")"
} > "$OUTPUT"

echo "Wrote ${OUTPUT#"$ROOT/"}"
